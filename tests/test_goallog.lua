test("goal log selects new goals and survives deletes", function()
    local env = setup()
    local FC = env.FC
    env.slash("")                       -- open window
    FC:Toggle("goals")
    env.slash("goal level 20")
    env.slash("goal Buy a mount")
    local mode, sel = FC:GetWindowState()
    eq(mode, "goals", "goals tab")
    eq(sel, 2, "newest goal selected")
    env.slash("del 2")
    mode, sel = FC:GetWindowState()
    eq(sel, 1, "selection moves to a remaining goal")
    env.slash("del 1")
    mode, sel = FC:GetWindowState()
    eq(sel, nil, "nothing selected when empty")
end)

test("goal descriptions are saved and trimmed", function()
    local env = setup()
    local FC = env.FC
    env.slash("goal Buy a mount")
    FC:SetGoalDescription(1, "  Need 90 gold  ")
    eq(FC.db.goals[1].description, "Need 90 gold", "trimmed")
    FC:SetGoalDescription(1, "   ")
    eq(FC.db.goals[1].description, nil, "blank clears")
end)

test("goal type descriptions", function()
    local env = setup()
    local FC = env.FC
    env.slash("goal level 20"); env.slash("goal quest 123"); env.slash("goal here"); env.slash("goal Something")
    ok(FC:DescribeGoalType(FC.db.goals[1]):find("level 20"), "level")
    ok(FC:DescribeGoalType(FC.db.goals[2]):find("quest ID 123"), "quest id")
    ok(FC:DescribeGoalType(FC.db.goals[3]):find("20 yd"), "location")
    ok(FC:DescribeGoalType(FC.db.goals[4]):find("Personal"), "free")
end)

test("reopening a goal via toggle", function()
    local env = setup()
    env.slash("goal A"); env.slash("done 1")
    env.FC:ToggleGoal(1)
    eq(env.FC.db.goals[1].done, false, "reopened")
    eq(env.FC.db.goals[1].completed, nil, "completion cleared")
end)
