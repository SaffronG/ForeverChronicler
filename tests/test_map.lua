test("map pins: zone, continent, off-map, click, refresh", function()
    local env = setup()
    env.slash("goal 20 30"); env.slash("goal 80 80"); env.slash("goal level 99")
    eq(#env.pins, 2, "two pins on zone map")
    eq(env.pins[1].x, 0.2, "pin x")
    eq(env.pins[1].texture, "Interface\\TargetingFrame\\UI-RaidTargetingIcon_1", "icon")
    env.mapID = 2; env.pinProvider:RefreshAllData()
    eq(env.pins[2].x, 0.2, "projected onto continent (0.8 * 1000 / 4000)")
    env.mapID = 3; env.pinProvider:RefreshAllData()
    eq(#env.pins, 0, "hidden off-map")
    env.mapID = 1; env.pinProvider:RefreshAllData()
    env.pins[2]:OnMouseEnter()
    ok(env.tooltip:find("80.0, 80.0", 1, true), "tooltip")
    env.pins[1]:OnMouseUp("LeftButton", true)
    eq(env.waypoint.position.x, 0.2, "click sets waypoint")
    env.pins[2]:OnMouseUp("RightButton", true)
    eq(env.waypoint.position.x, 0.2, "right-click ignored")
    env.slash("del 1")
    eq(#env.pins, 1, "pin removed on delete")
    env.pins[1]:OnMouseUp("LeftButton", true)
    eq(env.waypoint.position.x, 0.8, "indexes shifted correctly")
end)
