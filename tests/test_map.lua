    ok(env.chatContains("Coordinates go from 0 to 100."), "range check")
    env.player.map = nil
    env.slash("goal here")
    ok(env.chatContains("instances hide it"), "no position in instance")
    eq(#env.FC.db.goals, 1, "no bad goals created")
end)

test("ctrl+right-click world map menu restores zoom and creates goal", function()
    local env = setup()
    local sc = WorldMapFrame.ScrollContainer
    env.ctrl = true; env.cursorX, env.cursorY = 0.8, 0.8
    sc.hooks.OnMouseDown(sc, "RightButton")
    env.mapID = 2 -- the map zooms out on right-click
    sc.hooks.OnMouseUp(sc, "RightButton")
    eq(env.mapID, 1, "zoom restored")
    local menu = env.menus[1]
    ok(menu, "menu shown")
    menu.buttons["Set as goal: travel here"]()
    eq(env.FC.db.goals[1].target.x, 0.8, "goal from map")
    env.ctrl = false
    sc.hooks.OnMouseDown(sc, "RightButton"); sc.hooks.OnMouseUp(sc, "RightButton")
    eq(#env.menus, 1, "plain right-click shows no menu")
end)

